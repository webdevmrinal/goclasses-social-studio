import {createHash} from 'node:crypto';
import fs from 'node:fs/promises';
import sharp from 'sharp';
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const failure=()=>new Error('Telegram image count, content or order does not match the reviewed selection. Nothing was sent.');
export async function telegramPhotoSources(files){return Promise.all(files.map(async file=>{const bytes=await fs.readFile(file);return {bytes,hash:hash(bytes)};}));}
async function previews(dialog,count){
  const end=Date.now()+30000;
  do{
    const images=await dialog.locator('.popup-photo .popup-item-media img').evaluateAll(async images=>Promise.all(images.map(async img=>{
      if(!img.complete||!img.naturalWidth||!img.src.startsWith('blob:'))return null;
      const response=await fetch(img.src);if(!response.ok)return null;
      const bytes=new Uint8Array(await response.arrayBuffer());let raw='';
      for(let i=0;i<bytes.length;i+=32768)raw+=String.fromCharCode(...bytes.subarray(i,i+32768));
      return {data:btoa(raw),width:img.naturalWidth,height:img.naturalHeight};
    })));
    if(images.length===count&&images.every(Boolean))return images.map(image=>{const bytes=Buffer.from(image.data,'base64');return {...image,data:undefined,bytes,hash:hash(bytes)};});
    if(images.length>count)throw failure();
    if(Date.now()>=end)throw failure();
    await new Promise(resolve=>setTimeout(resolve,200));
  }while(true);
}
function difference(a,b){
  if(a.length!==b.length)return {mean:Infinity,rms:Infinity};let sum=0,squared=0;
  for(let i=0;i<a.length;i++){const d=a[i]-b[i];sum+=Math.abs(d);squared+=d*d;}
  return {mean:sum/a.length,rms:Math.sqrt(squared/a.length)};
}
async function matches(source,preview){
  if(source.hash===preview.hash)return true;
  // Telegram Web creates a resized JPEG even when a PNG was selected. Verify
  // decoded content once, then pin the exact generated bytes for every preflight.
  const meta=await sharp(source.bytes).autoOrient().metadata();
  const original=meta.autoOrient||meta;
  if(preview.width>original.width||preview.height>original.height||Math.abs(preview.width/preview.height-original.width/original.height)>.005)return false;
  for(const background of meta.hasAlpha?['#ffffff','#000000']:['#ffffff']){
    const decode=bytes=>sharp(bytes).autoOrient().flatten({background}).toColourspace('srgb').resize(preview.width,preview.height,{fit:'fill'});
    const [expected,actual]=await Promise.all([decode(source.bytes).raw().toBuffer(),decode(preview.bytes).raw().toBuffer()]);
    // Resize decoded pixels, avoiding different JPEG shrink-on-load paths.
    const reduced=bytes=>sharp(bytes,{raw:{width:preview.width,height:preview.height,channels:3}}).resize(96,96,{fit:'fill'}).raw().toBuffer();
    const [smallExpected,smallActual]=await Promise.all([reduced(expected),reduced(actual)]);
    const full=difference(expected,actual),small=difference(smallExpected,smallActual);
    if(full.mean<=5&&full.rms<=12&&small.mean<=3.5&&small.rms<=5)return true;
  }
  return false;
}
export async function verifyTelegramPhotos(dialog,sources,evidence){
  const actual=await previews(dialog,sources.length);
  for(let i=0;i<actual.length;i++){
    if(evidence?actual[i].hash!==evidence[i]?.hash:!await matches(sources[i],actual[i]))throw failure();
  }
  if(sources.length>1&&(await dialog.locator('.popup-photo > .popup-item-album').count()!==1||await dialog.locator('.popup-photo > .popup-item-album > .popup-item-media').count()!==sources.length))throw new Error('Telegram images are not grouped into one reviewed album. Nothing was sent.');
  return actual.map(({hash,width,height})=>({hash,width,height}));
}
